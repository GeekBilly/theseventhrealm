ACTION = {
    "A": "录原文·可上线",
    "B": "只书目·不上全文",
    "C": "可录可上线（官方文件）",
    "D": "只条目·不复刻图像",
}


def main():
    rows = list(csv.DictReader(open(HERE / "citations.csv", encoding="utf-8")))
    cnt = collections.Counter(r["书名"] for r in rows)
    out = HERE / "canon.csv"
    with open(out, "w", encoding="utf-8", newline="") as f:
        w = csv.writer(f)
        w.writerow(["书名", "引用次数", "类别", "处理方式", "形态", "成书年代",
                    "作者", "母书", "备注"])
        for name, n in sorted(cnt.items(), key=lambda kv: (-kv[1], kv[0])):
            c = CANON.get(name)
            if c is None:
                w.writerow([name, n, "?", "待定", "待定", "", "", "", "未分类，需补"])
                print("  ⚠ 未分类：%s" % name)
                continue
            cat, form, era, author, parent, note = c
            w.writerow([name, n, cat, ACTION[cat], form, era, author, parent, note])
    stat = collections.Counter()
    for name in cnt:
        c = CANON.get(name)
        stat[c[0] if c else "?"] += 1
    print("写出 %s" % out)
    print("按类别：", dict(stat))
    print("引用总数：%d 条 / 书名 %d 种" % (sum(cnt.values()), len(cnt)))
    # 估算可录原文的条目数
    a = sum(n for name, n in cnt.items() if CANON.get(name, ("?",))[0] in ("A", "C"))
    b = sum(n for name, n in cnt.items() if CANON.get(name, ("?",))[0] == "B")
    d = sum(n for name, n in cnt.items() if CANON.get(name, ("?",))[0] == "D")
    print("需录原文 %d 条 / 只书目 %d 条 / 只条目 %d 条" % (a, b, d))


if __name__ == "__main__":
    main()
